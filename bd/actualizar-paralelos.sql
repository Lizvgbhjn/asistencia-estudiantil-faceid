USE asistencia;

ALTER TABLE materia
    ADD COLUMN IF NOT EXISTS cupos_a SMALLINT UNSIGNED NOT NULL DEFAULT 30,
    ADD COLUMN IF NOT EXISTS cupos_b SMALLINT UNSIGNED NOT NULL DEFAULT 30;

ALTER TABLE clase
    ADD COLUMN IF NOT EXISTS paralelo ENUM('A','B') NOT NULL DEFAULT 'A';

ALTER TABLE matricula
    MODIFY COLUMN estado ENUM('PENDIENTE','APROBADA','RECHAZADA','RETIRADA','HABILITADA','RESERVADA') NOT NULL,
    ADD COLUMN IF NOT EXISTS foto_matricula MEDIUMBLOB,
    ADD COLUMN IF NOT EXISTS paralelo ENUM('A','B');

UPDATE matricula SET paralelo='A'
WHERE paralelo IS NULL AND (estado IN ('APROBADA','RETIRADA') OR (estado='PENDIENTE' AND foto_matricula IS NOT NULL));
